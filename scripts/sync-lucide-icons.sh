#!/usr/bin/env bash
#
# Vendor a pinned subset of lucide-static SVGs plus regenerate LucideIconName.swift.
#
# Usage: scripts/sync-lucide-icons.sh
#
# The icon list mirrors the epic table in mourato/GitMenuBar#22. Only interface
# icons live here; brand logos (ProviderIcon-*) and @pierre/trees file-type
# artwork stay out by policy (see docs/lucide-icons.md).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

LUCIDE_VERSION="1.72.0"
BASE_URL="https://unpkg.com/lucide-static@${LUCIDE_VERSION}/icons"
OUT_DIR="GitMenuBar/Resources/LucideIcons"
ENUM_FILE="GitMenuBar/Components/Common/LucideIconName.swift"

ICONS=(
    app-window
    archive
    arrow-down
    arrow-left-right
    arrow-up
    ban
    box-select
    check
    chevron-down
    chevron-left
    chevron-right
    chevron-up
    circle-alert
    circle-arrow-down
    circle-arrow-up
    circle-check
    circle-dot
    circle-help
    circle-minus
    circle-plus
    circle-user-round
    circle-x
    cloud
    copy
    diff
    ellipsis
    equal
    eye
    eye-off
    file
    file-check
    file-cog
    file-plus
    file-text
    folder
    folder-open
    folder-plus
    gauge
    git-branch
    git-pull-request
    globe
    house
    info
    keyboard
    layers
    lock
    map-pin
    octagon-x
    paintbrush
    pencil
    plus
    power
    refresh-cw
    search
    settings
    sparkles
    tag
    text-cursor
    trash-2
    triangle-alert
    undo-2
    wand-sparkles
    x
    zap
)

mkdir -p "$OUT_DIR"

echo "Syncing ${#ICONS[@]} icons from lucide-static@${LUCIDE_VERSION}..."
for icon in "${ICONS[@]}"; do
    curl --fail --silent --show-error --location \
        --output "${OUT_DIR}/${icon}.svg" \
        "${BASE_URL}/${icon}.svg"
done

python3 - "$LUCIDE_VERSION" "$ENUM_FILE" "${ICONS[@]}" <<'EOF'
import re
import sys

version = sys.argv[1]
enum_file = sys.argv[2]
icons = sys.argv[3:]


def case_name(icon: str) -> str:
    parts = icon.split("-")
    return parts[0] + "".join(word.capitalize() for word in parts[1:])


lines = [
    "// Generated by scripts/sync-lucide-icons.sh from",
    f"// lucide-static {version}. Do not edit by hand.",
    "// swiftformat:disable redundantRawValues",
    "enum LucideIconName: String, CaseIterable, Sendable {",
]
for icon in icons:
    name = case_name(icon)
    if len(name) < 2:
        lines.append("    // swiftlint:disable:next identifier_name")
    lines.append(f"    case {name} = \"{icon}\"")
lines.append("}")
with open(enum_file, "w", encoding="utf-8") as handle:
    handle.write("\n".join(lines) + "\n")
EOF

echo "Wrote ${OUT_DIR}/ (${#ICONS[@]} SVGs) and ${ENUM_FILE}."
